"""官方初始狀態若不是 EarthMJ2000Eq 笛卡兒（例如 GMAT 教育訓練錄影 (4) 示範的 EarthFixed + SphericalAZFPA
經緯高格式），用 GmatConsole 原樣建成 Spacecraft、回報 EarthMJ2000Eq 笛卡兒——地球自轉、歲差章動跟 GMAT 一致。

輸入 JSON（每艘的欄位名與值原樣寫進 GMAT 的 Spacecraft）：

    {"pursuer": {"DateFormat": "UTCGregorian", "Epoch": "09 Nov 2026 00:00:00.000",
                 "CoordinateSystem": "EarthFixed", "DisplayStateType": "SphericalAZFPA",
                 "RMAG": 6871, "RA": 120, "DEC": 23.5, "VMAG": 7.2, "AZI": 90, "FPA": 90},
     "evader": {...}}

SphericalAZFPA 在 R2026a 的欄位：RMAG（km，地心距離）、RA（EarthFixed 下就是經度，度）、DEC（緯度，度）、
VMAG（km/s，EarthFixed 下是扣除地球自轉的速度）、AZI（方位角，從北往東，度）、FPA（飛行角，從徑向量起，
水平 = 90°）。輸出是 game.initial_state.align_initial_states 吃的格式（epoch 為 ISO 8601 UTC、r_km、v_kms），
可直接接著做 epoch 對齊。

用法：
    uv run python tools/gmat_state_convert.py input.json --out initial.json [--gmat-console PATH]
"""
import argparse
import json
import os
import re
import subprocess
import sys
import tempfile

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from tools.gmat_verify import GMAT_CONSOLE  # noqa: E402

SHIPS = {"pursuer": "ShipP", "evader": "ShipE"}
_FIELD_RE = re.compile(r"^[A-Za-z][A-Za-z0-9_]*$")
_BAD_CHARS = set("'\";\n\r%")
QUOTED_FIELDS = ("Epoch",)                       # GMAT 寫法要加單引號的字串欄位
# GMAT 存檔的順序：先曆元格式、曆元、座標系、狀態型式，再狀態分量（後面的分量才照前面的設定解讀）
LEADING_FIELDS = ("DateFormat", "Epoch", "CoordinateSystem", "DisplayStateType")
_STATE = ("X", "Y", "Z", "VX", "VY", "VZ")
REPORT_COLS = ["UTCModJulian"] + [f"EarthMJ2000Eq.{f}" for f in _STATE] + ["UTCGregorian"]


def _format_value(key, val):
    if isinstance(val, bool):
        raise ValueError(f"{key} 的值不能是布林：{val!r}")
    if isinstance(val, (int, float)):
        if not np.isfinite(val):
            raise ValueError(f"{key} 的值不是有限數字：{val!r}")
        s = repr(val) if isinstance(val, float) else str(val)
        return f"'{s}'" if key in QUOTED_FIELDS else s
    if isinstance(val, str):
        if not val.isascii() or _BAD_CHARS & set(val) or not val.strip():
            raise ValueError(f"{key} 的值 {val!r} 不合法：只能是不含引號／分號／換行／% 的 ASCII 字串")
        return f"'{val.strip()}'" if key in QUOTED_FIELDS else val.strip()
    raise ValueError(f"{key} 的值只能是數字或字串，收到 {type(val).__name__}")


def spacecraft_lines(name, fields):
    """一艘的 Create Spacecraft 區塊。欄位名只接受 [A-Za-z][A-Za-z0-9_]*。"""
    if not isinstance(fields, dict) or not fields:
        raise ValueError(f"{name} 的欄位要是非空的 dict")
    for key in fields:
        if not isinstance(key, str) or not _FIELD_RE.match(key):
            raise ValueError(f"欄位名 {key!r} 不合法（只接受英數與底線、英文字母開頭）")
    order = [k for k in LEADING_FIELDS if k in fields] + [k for k in fields if k not in LEADING_FIELDS]
    return [f"Create Spacecraft {name};"] + [f"{name}.{k} = {_format_value(k, fields[k])};" for k in order]


def convert_script(spec, report_path):
    """輸入 dict → GMAT 腳本：兩艘建好後不傳播，各 Report 一列（UTCModJulian、EarthMJ2000Eq 笛卡兒、UTCGregorian）。"""
    if any(c in str(report_path) for c in "'\n;"):
        raise ValueError(f"報表路徑不能含引號／分號／換行：{report_path!r}")
    missing = [s for s in SHIPS if s not in spec]
    if missing:
        raise ValueError(f"輸入缺 {missing}（要 pursuer 與 evader）")
    parts = ["% Auto-generated by ODC_GMAT_DRL tools/gmat_state_convert.py - initial state conversion"]
    for side, ship in SHIPS.items():
        parts += spacecraft_lines(ship, spec[side])
    parts += ["Create ReportFile Rep;", f"Rep.Filename = '{report_path}';", "Rep.WriteHeaders = false;",
              "Rep.Precision = 16;", "Rep.ColumnWidth = 26;", "BeginMissionSequence;"]
    for ship in SHIPS.values():
        parts.append(f"Report Rep {' '.join(f'{ship}.{c}' for c in REPORT_COLS)};")
    script = "\n".join(parts) + "\n"
    script.encode("ascii")
    return script


def parse_report(text):
    """報表文字 → {"pursuer": {...}, "evader": {...}}。

    每列 = UTCModJulian、X Y Z VX VY VZ（數字），最後的 UTCGregorian 是含空白的文字（例
    `09 Nov 2026 00:00:00.000`，佔 4 個 token），所以先取前 7 個數字、剩下的接回去當曆元字串。
    epoch 用 UTCModJulian 換算（精度到微秒），並跟 UTCGregorian 對照（差 > 1 ms 就報錯）。"""
    from game.initial_state import parse_epoch
    rows = [ln.split() for ln in text.splitlines() if ln.strip()]
    if len(rows) != len(SHIPS):
        raise ValueError(f"GMAT 報表應有 {len(SHIPS)} 列，收到 {len(rows)} 列")
    out = {}
    for side, toks in zip(SHIPS, rows):
        if len(toks) < 8:
            raise ValueError(f"{side} 的報表列欄位不足：{' '.join(toks)!r}")
        try:
            nums = [float(x) for x in toks[:7]]
        except ValueError as exc:
            raise ValueError(f"{side} 的報表列前 7 欄不是數字：{' '.join(toks)!r}") from exc
        if not np.all(np.isfinite(nums)):
            raise ValueError(f"{side} 的報表有非有限數值")
        greg = " ".join(toks[7:])
        epoch = parse_epoch(nums[0])
        if abs((epoch - parse_epoch(greg)).total_seconds()) > 1e-3:
            raise ValueError(f"{side} 的 UTCModJulian {nums[0]} 跟 UTCGregorian {greg!r} 對不起來")
        out[side] = {"epoch": epoch.isoformat().replace("+00:00", "Z"), "epoch_utc_gregorian": greg,
                     "r_km": nums[1:4], "v_kms": nums[4:7]}
    return out


def run_convert(spec, console=GMAT_CONSOLE, timeout=120):
    """跑 GmatConsole 轉換；回傳 parse_report 的結果。console 路徑可以含空白（Mac）。"""
    if not os.path.exists(console):
        raise FileNotFoundError(f"找不到 GmatConsole：{console}（可用 --gmat-console 或環境變數 GMAT_CONSOLE 指定）")
    with tempfile.TemporaryDirectory(prefix="gmat_convert_") as td:
        rep = os.path.join(td, "convert_report.txt")
        spath = os.path.join(td, "convert.script")
        with open(spath, "w") as f:
            f.write(convert_script(spec, rep))
        res = subprocess.run([console, "--exit", "--run", spath], cwd=os.path.dirname(console),
                             capture_output=True, text=True, timeout=timeout)
        if res.returncode != 0 or not os.path.exists(rep):
            tail = "\n".join((res.stdout or "").strip().splitlines()[-20:])
            raise RuntimeError(f"GMAT 執行失敗（exit {res.returncode}）：\n{tail}")
        with open(rep, encoding="utf-8", errors="replace") as f:
            return parse_report(f.read())


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("input", help="輸入 JSON（pursuer / evader 的 GMAT Spacecraft 欄位）")
    ap.add_argument("--out", default=None, help="輸出 JSON 路徑（預設印到 stdout）")
    ap.add_argument("--gmat-console", default=GMAT_CONSOLE)
    args = ap.parse_args()
    with open(args.input, encoding="utf-8") as f:
        spec = json.load(f)
    out = run_convert(spec, console=args.gmat_console)
    text = json.dumps(out, ensure_ascii=False, indent=2)
    if args.out:
        with open(args.out, "w", encoding="utf-8") as f:
            f.write(text + "\n")
        print(f"→ {args.out}", file=sys.stderr)
    else:
        print(text)
    for side, st in out.items():
        print(f"{side}: epoch {st['epoch']}  |r| = {np.linalg.norm(st['r_km']):.6f} km  "
              f"|v| = {np.linalg.norm(st['v_kms']):.9f} km/s", file=sys.stderr)


if __name__ == "__main__":
    main()
